"""Converts the generated art in assets/ into phone-sized WebP files in img/.

Run:  python tools/process_assets.py
- removes flat #00FF00 / #FF00FF key-color backgrounds (for tools without transparency)
- shrinks every image (keeping its full canvas, so grade variants stay aligned)
- writes imglist.js so the game knows which images exist
"""
import glob
import os

from PIL import Image

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
SRC, OUT = os.path.join(ROOT, 'assets'), os.path.join(ROOT, 'img')
SIZES = {'ui/lobby_bg': (540, 960), 'ui/logo': (512, 256)}
DEFAULT = (256, 256)
KEYS = [(0, 255, 0), (255, 0, 255)]


def remove_key(im):
    """Make a flat key-color background transparent, if the corners show one."""
    px = im.load()
    w, h = im.size
    corners = [px[2, 2], px[w - 3, 2], px[2, h - 3], px[w - 3, h - 3]]
    if any(c[3] < 250 for c in corners):
        return im  # already transparent
    for key in KEYS:
        if all(sum(abs(a - b) for a, b in zip(c[:3], key)) < 90 for c in corners):
            break
    else:
        return im  # a full picture, keep as is
    for y in range(h):
        for x in range(w):
            r, g, b, a = px[x, y]
            d = abs(r - key[0]) + abs(g - key[1]) + abs(b - key[2])
            if d < 120:
                px[x, y] = (r, g, b, 0)
            elif d < 260:  # soften the fringe and remove color spill
                if key == (0, 255, 0):
                    g = min(g, max(r, b))
                else:
                    r = min(r, g + 40); b = min(b, g + 40)
                px[x, y] = (r, g, b, int(a * (d - 120) / 140))
    return im


def main():
    os.makedirs(OUT, exist_ok=True)
    keys = []
    for src in sorted(glob.glob(os.path.join(SRC, '**', '*.png'), recursive=True)):
        rel = os.path.relpath(src, SRC).replace(os.sep, '/')[:-4]
        im = remove_key(Image.open(src).convert('RGBA'))
        size = SIZES.get(rel, DEFAULT)
        im = im.resize(size, Image.LANCZOS)
        dst = os.path.join(OUT, rel + '.webp')
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        im.save(dst, 'WEBP', quality=88, method=6)
        keys.append(rel)
        print(f'{rel}: {os.path.getsize(dst) // 1024}KB')
    with open(os.path.join(ROOT, 'imglist.js'), 'w', encoding='utf-8', newline='\n') as f:
        f.write('// generated by tools/process_assets.py — images available in img/\n')
        f.write('const IMG_LIST = ' + repr(keys).replace("'", '"') + ';\n')
    print(len(keys), 'images')


if __name__ == '__main__':
    main()
