"""Converts the generated art in assets/ into phone-sized WebP files in img/.

Run:  python tools/process_assets.py
- removes flat #00FF00 / #FF00FF key-color backgrounds (for tools without transparency)
- shrinks every image (keeping its full canvas, so grade variants stay aligned)
- writes imglist.js so the game knows which images exist
"""
import glob
import os
import sys

from PIL import Image, ImageChops, ImageDraw

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
SRC, OUT = os.path.join(ROOT, 'assets'), os.path.join(ROOT, 'img')
SIZES = {'ui/lobby_bg': (540, 960), 'ui/logo': (512, 256)}
DEFAULT = (256, 256)
KEYS = [(0, 255, 0), (255, 0, 255)]


def remove_key(im):
    """Make a flat key-color background transparent, if the corners show one."""
    px = im.load()
    w, h = im.size
    corners = [px[2, 2], px[w - 3, 2], px[2, h - 3], px[w - 3, h - 3]]
    if any(c[3] < 250 for c in corners):
        return im  # already transparent
    for key in KEYS:
        if all(sum(abs(a - b) for a, b in zip(c[:3], key)) < 90 for c in corners):
            break
    else:
        return im  # a full picture, keep as is
    for y in range(h):
        for x in range(w):
            r, g, b, a = px[x, y]
            d = abs(r - key[0]) + abs(g - key[1]) + abs(b - key[2])
            if d < 120:
                px[x, y] = (r, g, b, 0)
            elif d < 260:  # soften the fringe and remove color spill
                if key == (0, 255, 0):
                    g = min(g, max(r, b))
                else:
                    r = min(r, g + 40); b = min(b, g + 40)
                px[x, y] = (r, g, b, int(a * (d - 120) / 140))
    return im


_FADE = {}


def fade_glow(im):
    """Fade faint glow/ray backgrounds into a soft circle so no square box shows in game.
    Solid pixels (the item itself) are left untouched."""
    w, h = im.size
    mask = _FADE.get((w, h))
    if mask is None:
        mask = Image.new('L', (w, h), 0)
        d = ImageDraw.Draw(mask)
        steps = 40
        for i in range(steps):  # concentric circles: 255 in the middle, 0 at the edge
            r = (0.95 - 0.4 * i / steps) * w / 2
            d.ellipse([w / 2 - r, h / 2 - r, w / 2 + r, h / 2 + r], fill=int(255 * i / steps))
        _FADE[(w, h)] = mask
    alpha = im.getchannel('A')
    solid = alpha.point(lambda v: 255 if v >= 150 else 0)
    im.putalpha(Image.composite(alpha, ImageChops.multiply(alpha, mask), solid))
    return im


def main():
    force = '--force' in sys.argv
    os.makedirs(OUT, exist_ok=True)
    keys = []
    for src in sorted(glob.glob(os.path.join(SRC, '**', '*.png'), recursive=True)):
        rel = os.path.relpath(src, SRC).replace(os.sep, '/')[:-4]
        dst = os.path.join(OUT, rel + '.webp')
        keys.append(rel)
        if not force and os.path.exists(dst) and os.path.getmtime(dst) >= os.path.getmtime(src):
            continue  # already converted
        im = remove_key(Image.open(src).convert('RGBA'))
        if rel.startswith(('weapons/', 'equip/')):
            im = fade_glow(im)
        im = im.resize(SIZES.get(rel, DEFAULT), Image.LANCZOS)
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        im.save(dst, 'WEBP', quality=88, method=4)
        print(f'{rel}: {os.path.getsize(dst) // 1024}KB')
    # where each character's visible content ends (fraction of the image height),
    # so the game can stand it on the ground however it was framed
    bottoms = {}
    for rel in keys:
        if rel.split('/')[0] in ('heroes', 'pets', 'monsters', 'bosses'):
            im = Image.open(os.path.join(OUT, rel + '.webp'))
            box = im.getchannel('A').point(lambda v: 255 if v > 200 else 0).getbbox()  # solid pixels only, not glow
            if box:
                bottoms[rel] = round(box[3] / im.height, 3)
    with open(os.path.join(ROOT, 'imglist.js'), 'w', encoding='utf-8', newline='\n') as f:
        f.write('// generated by tools/process_assets.py — images available in img/\n')
        f.write('const IMG_LIST = ' + repr(keys).replace("'", '"') + ';\n')
        f.write('const IMG_BOTTOM = ' + repr(bottoms).replace("'", '"') + ';\n')
    print(len(keys), 'images')


if __name__ == '__main__':
    main()
